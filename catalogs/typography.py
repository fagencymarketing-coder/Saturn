# -*- coding: utf-8 -*-
"""Единое оформление значений прайса.

🔴 Правило (заказчик, 2026-09-28): СУТЬ — ровно как в подтверждённой таблице,
ОФОРМЛЕНИЕ — единое. Поэтому здесь правятся только знаки: валюта, тире,
склеенные единицы, лишние пробелы. Ни одна цифра и ни одно слово не меняются
и не сокращаются.

Тот же модуль подключён к verify_price_pdf.py, поэтому сверка идёт
«значение из таблицы после оформления» ↔ «значение в прайсе»: цифры
по-прежнему проверяются буква в букву.
"""
import re

# «л/кг/га» в таблице СЗР означает «литров (или килограммов) на гектар»:
# три единицы, склеенные подряд, читаются как несуществующая единица.
GLUED_UNITS = re.compile(r'\bл/кг/га\b')

# дефис-минус между числами — это диапазон, набирается коротким тире без пробелов
RANGE = re.compile(r'(?<=\d)\s*-\s*(?=\d)')

CURRENCY = re.compile(r'(?<=\d)\s*(?:руб\.?|р\.|р)(?![а-яё])', re.I)

# цена, в которой есть число, но нет ни знака рубля, ни слова «запрос»
BARE_PRICE = re.compile(r'^((?:от\s*)?[\d\s.,]+)$')


# случайные иероглифы в русском тексте — опечатка ввода. В таблице заказчика
# нашёлся один: «Обработка семян всех基 полевых культур» (Микромак, 29.09).
CJK = re.compile(r'[\u3000-\u9fff\uac00-\ud7af]')


def polish(v):
    """Общее оформление для любого текстового значения прайса."""
    if v is None:
        return ''
    s = CJK.sub('', str(v))
    s = GLUED_UNITS.sub('л (кг)/га', s)
    s = RANGE.sub('–', s)
    s = re.sub(r'[ \t]{2,}', ' ', s)
    return s.strip()


def price(v):
    """Оформление колонки «Цена»: единый знак ₽ и единая формулировка запроса."""
    s = polish(v)
    if not s:
        return ''
    if 'запрос' in s.lower():
        return 'Цена по запросу'
    s = CURRENCY.sub(' ₽', s)
    m = BARE_PRICE.match(s)
    if m:
        s = m.group(1).strip() + ' ₽'
    return re.sub(r'\s+', ' ', s).strip()
