from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

ORANGE = RGBColor(0xC4,0x3C,0x08)
INK = RGBColor(0x22,0x1C,0x16)
GREY = RGBColor(0x60,0x60,0x60)

def new_doc():
    d = Document()
    st = d.styles['Normal']
    st.font.name = 'Calibri'
    st.font.size = Pt(11)
    return d

def h1(d,t):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=True; r.font.size=Pt(20); r.font.color.rgb=INK
    p.space_after=Pt(4); return p
def sub(d,t):
    p=d.add_paragraph(); r=p.add_run(t); r.font.size=Pt(11); r.font.color.rgb=GREY; return p
def h2(d,t):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=True; r.font.size=Pt(14); r.font.color.rgb=ORANGE
    return p
def h3(d,t):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=True; r.font.size=Pt(11.5); r.font.color.rgb=INK
    return p
def para(d,t,bold=False):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=bold; return p
def bullet(d,t):
    p=d.add_paragraph(style='List Bullet'); p.add_run(t); return p
def num(d,t):
    p=d.add_paragraph(style='List Number'); p.add_run(t); return p
def kv(d,k,v):
    p=d.add_paragraph(); r=p.add_run(k+': '); r.bold=True; p.add_run(v); return p
def rule(d):
    p=d.add_paragraph(); r=p.add_run('—'*40); r.font.color.rgb=RGBColor(0xCC,0xCC,0xCC); return p

