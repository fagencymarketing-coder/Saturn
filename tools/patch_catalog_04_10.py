rows = list(csv.DictReader(io.open(SRC, encoding='utf-8-sig'), delimiter=';'))
cols = list(rows[0].keys())
log = []

def setcell(r, col, val, why):
    old = r.get(col, '')
    if old == val: return
    r[col] = val
    log.append((r['Title'], why, old or '(пусто)', val))

for r in rows:
    t = r['Title']
    if t in PRICE:
        num = PRICE[t]
        r['Price'] = num.replace(',', '.')
        txt = r['Text']
        m = re.search(r'Цена: *(от )?[\d  .,]+ ₽(/[^.\s]+)?', txt)
        if m:
            new = 'Цена: %s%s ₽%s' % (m.group(1) or '', num, m.group(2) or '')
            setcell(r, 'Text', txt[:m.start()] + new + txt[m.end():], 'цена')
        else:
            tail = 'Цена: от %s ₽/л. При 100%% предоплате, доставка и хранение включены.' % num
            setcell(r, 'Text', (txt + '<br><br>' + tail) if txt else tail, 'цена (добавлена)')
    if t in SOSTAV:  setcell(r, 'Characteristics:Состав', SOSTAV[t], 'состав')
    if t in SPEKTR:  setcell(r, 'Characteristics:Спектр действия', SPEKTR[t], 'спектр действия')
    if t in FASOVKA: setcell(r, 'Characteristics:Фасовка', FASOVKA[t], 'фасовка')

